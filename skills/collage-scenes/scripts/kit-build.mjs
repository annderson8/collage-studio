#!/usr/bin/env node
// Builds (or adds to) a series kit: decoration pieces cut once and reused by every reel of the series,
// so new scenes are generated without them and the layer split returns (and bills) fewer layers.
//
//   node kit-build.mjs <kit dir> <project> <name>=<layer png> [<name>=<layer png> ...]
//   e.g. node kit-build.mjs ../_kit . circle1=scenes/layers/03/circle.png news1=scenes/layers/02/news.png
//
// Each layer must be registered in <project>/scenes/manifest.json (it was imported with layers-import.mjs):
// its size and place in the frame come from there, converted to video pixels. The kind comes from the name:
// circle* / backdrop* → backdrop, lines* / arc* → lines, news* / scrap* → scrap, anything else → accent.
// Writes <kit>/<name>.png, <kit>/kit.json and <kit>/kit.js (window.KIT, read by collage.html from ../../_kit/).
import fs from 'fs';
import path from 'path';

const [kitArg, projArg, ...pairs] = process.argv.slice(2);
if (!kitArg || !projArg || !pairs.length) {
  console.error('usage: node kit-build.mjs <kit dir> <project> <name>=<layer png> ...'); process.exit(2);
}
const kit = path.resolve(kitArg), proj = path.resolve(projArg);
const man = JSON.parse(fs.readFileSync(path.join(proj, 'scenes/manifest.json'), 'utf8'));
let fmt = '9:16';
try { fmt = JSON.parse(fs.readFileSync(path.join(proj, 'style/style.json'), 'utf8')).format || fmt; } catch {}
const [W, H] = ({ '9:16': [1080, 1920], '1:1': [1080, 1080], '4:5': [1080, 1350], '16:9': [1920, 1080] })[fmt];

fs.mkdirSync(kit, { recursive: true });
const kf = path.join(kit, 'kit.json');
const out = fs.existsSync(kf) ? JSON.parse(fs.readFileSync(kf, 'utf8')) : { format: fmt, pieces: {} };
if (out.format !== fmt) { console.error(`kit is ${out.format}, project is ${fmt}: keep one kit per format`); process.exit(1); }

const kindOf = n => /^(circle|backdrop)/.test(n) ? 'backdrop' : /^(lines|arc)/.test(n) ? 'lines' : /^(news|scrap)/.test(n) ? 'scrap' : 'accent';
for (const pair of pairs) {
  const [name, file] = pair.split('=');
  if (!/^[a-z][a-z0-9]*$/.test(name || '') || !file) { console.error(`bad pair "${pair}" (name: lowercase letters and digits)`); process.exit(2); }
  const src = path.relative(proj, path.resolve(file)).split(path.sep).join('/');
  const m = Object.values(man.cutouts).find(c => c.src === src);
  if (!m) { console.error(`${src} is not in scenes/manifest.json: import that scene first`); process.exit(1); }
  const sc = Math.max(W / m.sceneW, H / m.sceneH);                       // cover-fit, as collage.html does
  fs.copyFileSync(path.resolve(file), path.join(kit, `${name}.png`));
  out.pieces[name] = {
    file: `${name}.png`, kind: kindOf(name),
    w: Math.round(m.w * sc), h: Math.round(m.h * sc),
    x: Math.round((m.x + m.w / 2) * sc - (m.sceneW * sc - W) / 2),     // centre in video pixels
    y: Math.round((m.y + m.h / 2) * sc - (m.sceneH * sc - H) / 2),
    from: `${path.basename(proj)}/${src}`,
  };
  console.log(`${name.padEnd(10)} ${out.pieces[name].kind.padEnd(8)} ${out.pieces[name].w}×${out.pieces[name].h} at ${out.pieces[name].x},${out.pieces[name].y}`);
}
fs.writeFileSync(kf, JSON.stringify(out, null, 1));
// paths in KIT are relative to a project root that sits next to the kit folder
const rel = '../' + path.basename(kit) + '/';
const pieces = Object.fromEntries(Object.entries(out.pieces).map(([k, p]) => [k, { ...p, src: rel + p.file }]));
fs.writeFileSync(path.join(kit, 'kit.js'), `// generated by collage-scenes/kit-build.mjs: do not edit by hand\nwindow.KIT = ${JSON.stringify(pieces)};\n`);
const kinds = Object.values(out.pieces).reduce((a, p) => (a[p.kind] = (a[p.kind] || 0) + 1, a), {});
console.log(`kit: ${Object.keys(out.pieces).length} pieces (${Object.entries(kinds).map(([k, n]) => `${n} ${k}`).join(', ')}) → ${kit}`);
