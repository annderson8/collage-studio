// Shared by cutout.mjs and layers-import.mjs: keeps scenes/manifest.json and scenes/manifest.js in sync.
//
// Project layout (see collage-reel): <project>/scenes/<id>.png, <project>/scenes/layers/<id>/{base.png, <piece>.png}
// manifest.json = { cutouts: { "<id>_<piece>": {src, x, y, w, h, sceneW, sceneH, scene, z, name} }, plates: { "<id>": src } }
// Every src is relative to the project root; collage.html (in <project>/build/) prefixes "../".

import fs from 'fs';
import path from 'path';

export function sceneInfo(sceneImage) {
  const scenesDir = path.dirname(path.resolve(sceneImage));
  const id = path.basename(sceneImage).replace(/\.[^.]+$/, '');
  return { scenesDir, root: path.dirname(scenesDir), id, layersDir: path.join(scenesDir, 'layers', id) };
}

export const rel = (root, file) => path.relative(root, path.resolve(file)).split(path.sep).join('/');

export function readManifest(scenesDir) {
  const f = path.join(scenesDir, 'manifest.json');
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : { cutouts: {}, plates: {} };
}

export function writeManifest(scenesDir, man) {
  fs.writeFileSync(path.join(scenesDir, 'manifest.json'), JSON.stringify(man, null, 1));
  fs.writeFileSync(path.join(scenesDir, 'manifest.js'),
    `// generated by collage-scenes: do not edit by hand\n` +
    `window.CUTOUTS = Object.assign(window.CUTOUTS || {}, ${JSON.stringify(man.cutouts)});\n` +
    `window.PLATES = Object.assign(window.PLATES || {}, ${JSON.stringify(man.plates)});\n`);
}
